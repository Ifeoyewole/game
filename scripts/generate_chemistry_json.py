def build_text(target_words: int = 5000) -> str:
    vocab = [word.strip().replace(" ", "") for word in WORDS]
    words: list[str] = []
    i = 0
    while len(words) < target_words:
        words.append(vocab[i % len(vocab)])
        i += 1
    return " ".join(words[:target_words])

def main() -> None:
    target = 5000
    text = build_text(target)
    data = {
        "title": "Chemistry 5000 Word Overview",
        "generated": "automated script",
        "note": "Word count enforced by repetition of single-word chemistry vocabulary",
        "word_count": len(text.split()),
        "content": text,
    }
    out_path = Path(__file__).resolve().parent.parent / "chemistry.json"
    out_path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"Wrote {data['word_count']} words to {out_path}")


if __name__ == "__main__":
    main()
