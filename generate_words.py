def matches_category(word, cat_key):
    filters = CATEGORY_FILTERS[cat_key]
    wl = word.lower()
    for sub in filters.get("contains", []):
        if sub in wl:
            return True
    for pre in filters.get("starts", []):
        if wl.startswith(pre):
            return True
    for suf in filters.get("ends", []):
        if wl.endswith(suf):
            return True
    return False

