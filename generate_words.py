"""
Generate category word files using a real English dictionary.
Downloads a word list, then filters into categories using curated seed words.
"""
import json, os, urllib.request

DICT_URL = "https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt"
DICT_FILE = "english_dict.txt"

def download_dict():
    if os.path.exists(DICT_FILE):
        with open(DICT_FILE) as f:
            return set(w.strip().lower() for w in f if w.strip().isalpha() and 3 <= len(w.strip()) <= 14)
    print("Downloading English dictionary...")
    urllib.request.urlretrieve(DICT_URL, DICT_FILE)
    with open(DICT_FILE) as f:
        words = set(w.strip().lower() for w in f if w.strip().isalpha() and 3 <= len(w.strip()) <= 14)
    print(f"Dictionary: {len(words)} words")
    return words

def load_seeds(filename):
    """Load existing category file as seeds if it exists."""
    if not os.path.exists(filename):
        return set()
    with open(filename) as f:
        data = json.load(f)
    if isinstance(data, list):
        if data and isinstance(data[0], str):
            return set(w.lower() for w in data if isinstance(w, str))
    return set()

def save(name, words):
    clean = sorted(set(w.lower() for w in words if w.isalpha() and 3 <= len(w) <= 14))
    with open(name, 'w') as f:
        json.dump(clean, f, indent=2)
    print(f"{name}: {len(clean)} words")

